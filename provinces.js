// =========================================================
// HÀM LẤY DANH SÁCH TỈNH
// =========================================================
function getProvinces() {
    return window.VIETNAM_PROVINCES.map(p => ({
        code: p.code,
        name: p.name,
        region: p.region
    }));
}

// =========================================================
// HÀM LẤY QUẬN/HUYỆN THEO TỈNH
// =========================================================
function getDistricts(provinceCode) {
    const province = window.VIETNAM_PROVINCES.find(p => p.code === provinceCode);
    return province ? province.districts : [];
}

// =========================================================
// HÀM TẠO DROPDOWN TỈNH
// =========================================================
function renderProvinceDropdown(selectElement, selectedCode = '') {
    const provinces = getProvinces();
    selectElement.innerHTML = '<option value="">-- Chọn Tỉnh/Thành phố --</option>';
    
    // Nhóm theo vùng miền
    const regions = { 'Bắc': [], 'Trung': [], 'Nam': [] };
    provinces.forEach(p => {
        if (regions[p.region]) regions[p.region].push(p);
    });
    
    Object.keys(regions).forEach(region => {
        if (regions[region].length === 0) return;
        
        const optgroup = document.createElement('optgroup');
        optgroup.label = `Miền ${region}`;
        
        regions[region].forEach(p => {
            const option = document.createElement('option');
            option.value = p.code;
            option.textContent = p.name;
            if (p.code === selectedCode) option.selected = true;
            optgroup.appendChild(option);
        });
        
        selectElement.appendChild(optgroup);
    });
}

// =========================================================
// HÀM TẠO DROPDOWN QUẬN/HUYỆN
// =========================================================
function renderDistrictDropdown(selectElement, provinceCode, selectedDistrict = '') {
    selectElement.innerHTML = '<option value="">-- Chọn Quận/Huyện --</option>';
    
    if (!provinceCode) return;
    
    const districts = getDistricts(provinceCode);
    districts.forEach(d => {
        const option = document.createElement('option');
        option.value = d;
        option.textContent = d;
        if (d === selectedDistrict) option.selected = true;
        selectElement.appendChild(option);
    });
}

